export function translate(locale: Locale, value: string): string {
  return locale === "en" ? english[value.trim()] || value : value;
}
export function stripLocale(path: string): string {
  return path === "/en" ? "/" : path.replace(/^\/en(?=\/)/, "");
}
export function localePath(path: string, locale: Locale): string {
  if (
    !path.startsWith("/") ||
    path.startsWith("//") ||
    /^\/(admin|backend|api|assets|auth)(\/|$)/.test(path)
  )
    return path;
  const plain = stripLocale(path);
  return locale === "en" ? "/en" + (plain === "/" ? "" : plain) : plain;
}
export function number(value: number, locale: Locale): string {
  return new Intl.NumberFormat(locale === "en" ? "en-US" : "fa-IR").format(
    value,
  );
}
export function localDate(value: Value, locale: Locale, full = false): string {
  const date = new Date(
    typeof value === "string" || typeof value === "number" ? value : "",
  );
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(
    locale === "en" ? "en-GB" : "fa-IR-u-ca-persian",
    {
      timeZone: "Asia/Tehran",
      year: "numeric",
      month: full ? "long" : "2-digit",
      day: "numeric",
      ...(full ? { weekday: "long" as const } : {}),
    },
  ).format(date);
}
